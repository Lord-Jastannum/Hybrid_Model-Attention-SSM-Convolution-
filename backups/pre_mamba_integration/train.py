
import csv
import math
import random
import time

import torch
import torch.nn as nn
from torch.utils.data import DataLoader, TensorDataset
from tokenizers import Tokenizer
import matplotlib.pyplot as plt

import config
from model import HybridModel


def set_seed(seed):
    random.seed(seed)
    torch.manual_seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def load_split(path):
    if not path.exists():
        raise FileNotFoundError(
            f"Dataset not found: {path}\n"
            "Run dataset.py before training."
        )

    # These files contain tensors generated by our own dataset.py.
    sequences = torch.load(path, map_location="cpu", weights_only=True)

    if sequences.ndim != 2:
        raise ValueError(
            f"Expected a 2D tensor in {path}, "
            f"got shape {tuple(sequences.shape)}"
        )

    expected_length = config.SEQUENCE_LENGTH + 1

    if sequences.shape[1] != expected_length:
        raise ValueError(
            f"{path.name} has sequence width {sequences.shape[1]}; "
            f"expected {expected_length}. "
            "Check config.SEQUENCE_LENGTH."
        )

    return TensorDataset(sequences)


def create_loader(path, batch_size, shuffle):
    dataset = load_split(path)

    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=0,
        pin_memory=(config.DEVICE.type == "cuda"),
        drop_last=False,
    )


def get_tokenizer_vocab_size():
    tokenizer = Tokenizer.from_file(str(config.TOKENIZER_PATH))
    return tokenizer.get_vocab_size()


def evaluate(model, loader, criterion):
    model.eval()

    total_loss = 0.0
    total_tokens = 0
    gate_sum = torch.zeros(3, dtype=torch.float64)

    with torch.no_grad():
        for (sequences,) in loader:
            sequences = sequences.to(
                config.DEVICE,
                non_blocking=True,
            )

            input_ids = sequences[:, :-1]
            targets = sequences[:, 1:]

            logits, all_gates = model(input_ids)

            loss = criterion(
                logits.reshape(-1, logits.size(-1)),
                targets.reshape(-1),
            )

            token_count = targets.numel()
            total_loss += loss.item() * token_count
            total_tokens += token_count

            # Collect mean branch weights for diagnostics.
            if all_gates:
                gates = torch.stack(all_gates, dim=0)
                gate_sum += (
                    gates.detach()
                    .double()
                    .mean(dim=(0, 1, 2))
                    .cpu()
                )

    mean_loss = total_loss / max(total_tokens, 1)
    perplexity = math.exp(min(mean_loss, 20.0))

    mean_gates = (
        (gate_sum / max(len(loader.dataset) and len(loader), 1))
        .tolist()
    )

    return mean_loss, perplexity, mean_gates


def main():
    set_seed(config.SEED)

    print("=" * 60)
    print("Adaptive Hybrid Model - WikiText-2 Training")
    print("=" * 60)
    print(f"Device: {config.DEVICE}")

    if config.DEVICE.type == "cuda":
        print(f"GPU: {torch.cuda.get_device_name(0)}")

    actual_vocab_size = get_tokenizer_vocab_size()
    print(f"Tokenizer vocabulary: {actual_vocab_size}")
    print(f"Configured vocabulary: {config.VOCAB_SIZE}")

    if actual_vocab_size != config.VOCAB_SIZE:
        raise ValueError(
            "Tokenizer and model vocabulary sizes do not match. "
            "Update config.VOCAB_SIZE to the tokenizer's actual size."
        )

    train_loader = create_loader(
        config.TRAIN_PATH,
        config.BATCH_SIZE,
        shuffle=True,
    )

    validation_loader = create_loader(
        config.VALIDATION_PATH,
        config.EVAL_BATCH_SIZE,
        shuffle=False,
    )

    test_loader = create_loader(
        config.TEST_PATH,
        config.EVAL_BATCH_SIZE,
        shuffle=False,
    )

    model = HybridModel(
        vocab_size=config.VOCAB_SIZE,
        dim=config.MODEL_DIM,
        num_layers=config.NUM_LAYERS,
        num_heads=config.NUM_HEADS,
    ).to(config.DEVICE)

    parameter_count = sum(
        parameter.numel()
        for parameter in model.parameters()
        if parameter.requires_grad
    )

    print(f"Trainable parameters: {parameter_count:,}")
    print(f"Training batches per epoch: {len(train_loader)}")

    criterion = nn.CrossEntropyLoss()

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=config.LEARNING_RATE,
        weight_decay=config.WEIGHT_DECAY,
    )

    history = []
    best_validation_loss = float("inf")
    best_checkpoint = config.CHECKPOINT_DIR / "best_model.pt"
    csv_path = config.LOG_DIR / "training_history.csv"

    with csv_path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(
            file,
            fieldnames=[
                "epoch",
                "train_loss",
                "validation_loss",
                "validation_perplexity",
                "epoch_seconds",
            ],
        )
        writer.writeheader()

        for epoch in range(1, config.EPOCHS + 1):
            model.train()
            start_time = time.time()

            total_loss = 0.0
            total_tokens = 0

            for step, (sequences,) in enumerate(train_loader, start=1):
                sequences = sequences.to(
                    config.DEVICE,
                    non_blocking=True,
                )

                input_ids = sequences[:, :-1]
                targets = sequences[:, 1:]

                optimizer.zero_grad(set_to_none=True)

                logits, _ = model(input_ids)

                loss = criterion(
                    logits.reshape(-1, logits.size(-1)),
                    targets.reshape(-1),
                )

                if not torch.isfinite(loss):
                    raise RuntimeError(
                        f"Non-finite loss at epoch {epoch}, "
                        f"step {step}: {loss.item()}"
                    )

                loss.backward()

                torch.nn.utils.clip_grad_norm_(
                    model.parameters(),
                    config.GRAD_CLIP,
                )

                optimizer.step()

                token_count = targets.numel()
                total_loss += loss.item() * token_count
                total_tokens += token_count

                if step == 1 or step % 100 == 0:
                    print(
                        f"Epoch {epoch}/{config.EPOCHS} | "
                        f"Step {step}/{len(train_loader)} | "
                        f"Loss: {loss.item():.4f}"
                    )

            train_loss = total_loss / max(total_tokens, 1)

            (
                validation_loss,
                validation_perplexity,
                _,
            ) = evaluate(
                model,
                validation_loader,
                criterion,
            )

            epoch_seconds = time.time() - start_time

            row = {
                "epoch": epoch,
                "train_loss": train_loss,
                "validation_loss": validation_loss,
                "validation_perplexity": validation_perplexity,
                "epoch_seconds": epoch_seconds,
            }

            history.append(row)
            writer.writerow(row)
            file.flush()

            print("\n" + "-" * 60)
            print(f"Epoch: {epoch}")
            print(f"Training loss: {train_loss:.4f}")
            print(f"Validation loss: {validation_loss:.4f}")
            print(f"Validation perplexity: {validation_perplexity:.2f}")
            print(f"Epoch time: {epoch_seconds:.1f} seconds")
            print("-" * 60 + "\n")

            if validation_loss < best_validation_loss:
                best_validation_loss = validation_loss

                torch.save(
                    {
                        "epoch": epoch,
                        "model_state_dict": model.state_dict(),
                        "optimizer_state_dict": optimizer.state_dict(),
                        "validation_loss": validation_loss,
                        "config": {
                            "vocab_size": config.VOCAB_SIZE,
                            "dim": config.MODEL_DIM,
                            "num_layers": config.NUM_LAYERS,
                            "num_heads": config.NUM_HEADS,
                            "sequence_length": config.SEQUENCE_LENGTH,
                        },
                    },
                    best_checkpoint,
                )

                print(f"Saved best checkpoint: {best_checkpoint}")

    # Plot training and validation losses.
    epochs = [row["epoch"] for row in history]
    train_losses = [row["train_loss"] for row in history]
    validation_losses = [
        row["validation_loss"] for row in history
    ]

    plt.figure(figsize=(8, 5))
    plt.plot(epochs, train_losses, marker="o", label="Training loss")
    plt.plot(
        epochs,
        validation_losses,
        marker="o",
        label="Validation loss",
    )
    plt.xlabel("Epoch")
    plt.ylabel("Cross-entropy loss")
    plt.title("WikiText-2 Training and Validation Loss")
    plt.grid(True)
    plt.legend()
    plt.tight_layout()

    plot_path = config.PLOT_DIR / "loss_curve.png"
    plt.savefig(plot_path, dpi=150)
    plt.close()

    # Reload the best checkpoint before the final test evaluation.
    checkpoint = torch.load(
        best_checkpoint,
        map_location=config.DEVICE,
        weights_only=True,
    )

    model.load_state_dict(checkpoint["model_state_dict"])

    test_loss, test_perplexity, test_gates = evaluate(
        model,
        test_loader,
        criterion,
    )

    print("\n" + "=" * 60)
    print("FINAL TEST RESULTS")
    print("=" * 60)
    print(f"Best epoch: {checkpoint['epoch']}")
    print(f"Test loss: {test_loss:.4f}")
    print(f"Test perplexity: {test_perplexity:.2f}")
    print(f"Mean gate weights [attention, SSM, conv]: {test_gates}")
    print(f"Training history: {csv_path}")
    print(f"Loss plot: {plot_path}")
    print("=" * 60)


if __name__ == "__main__":
    main()
